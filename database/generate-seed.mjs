// Regenerates database/seed.sql from the frontend's catalogue (frontend/src/lib/data.ts).
// Run after changing movies, theatres or snacks:  node database/generate-seed.mjs
// Needs Node 22.18+ (reads the TypeScript file directly).
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = await import(pathToFileURL(path.join(here, "../frontend/src/lib/data.ts")).href);

const q = (v) => (v === undefined || v === null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = ["-- Generated by database/generate-seed.mjs. Do not edit by hand.", "BEGIN;"];

for (const m of data.movies)
  lines.push(`INSERT OR REPLACE INTO movies (id, title, lang, genre, rating, duration, year, blurb, banner, trailer) VALUES (${[m.id, m.title, m.lang, m.genre, m.rating, m.duration, m.year, m.blurb, m.banner, m.trailer].map(q).join(", ")});`);
for (const [city, list] of Object.entries(data.cityTheatres)) {
  lines.push(`INSERT OR REPLACE INTO cities (name) VALUES (${q(city)});`);
  for (const t of list)
    lines.push(`INSERT OR REPLACE INTO theatres (id, city, name, km, formats, layout) VALUES (${[t.id, city, t.name, t.km, t.formats.join(","), t.layout].map(q).join(", ")});`);
}
for (const s of data.snacks)
  lines.push(`INSERT OR REPLACE INTO snacks (id, name, price, emoji) VALUES (${[s.id, s.name, s.price, s.emoji].map(q).join(", ")});`);
lines.push("COMMIT;", "");

writeFileSync(path.join(here, "seed.sql"), lines.join("\n"));
console.log(`seed.sql written: ${data.movies.length} movies, ${Object.values(data.cityTheatres).flat().length} theatres, ${data.snacks.length} snacks`);
